using System.Text.Json;
using System.Text.Json.Serialization;

namespace AlbionChatTranslator.Core.Translation;

public sealed record ModelFile(string Path, long Size, string Sha256);

/// <summary>One downloadable translation model, pinned to an exact Hugging Face commit.</summary>
public sealed record ModelPack(string Id, string Repo, string Revision, IReadOnlyList<ModelFile> Files)
{
    public long TotalSize => Files.Sum(f => f.Size);
}

public sealed record DirectionalPack(string Pack, string? Prefix);

/// <summary>One step of a translation route: run <see cref="Pack"/>, optionally forcing a target language token.</summary>
public sealed record RouteStep(ModelPack Pack, string? TargetPrefix);

/// <summary>
/// The pinned list of offline language packs (generated by tools/update_model_catalog.py,
/// embedded in the app so it cannot be tampered with on disk).
/// </summary>
public sealed class ModelCatalog
{
    private readonly Dictionary<string, ModelPack> _packs;
    private readonly Dictionary<string, string> _toEnglish;
    private readonly Dictionary<string, DirectionalPack> _fromEnglish;

    private ModelCatalog(CatalogJson json)
    {
        _packs = json.Packs.ToDictionary(p => p.Id, StringComparer.OrdinalIgnoreCase);
        _toEnglish = new(json.ToEnglish, StringComparer.OrdinalIgnoreCase);
        _fromEnglish = new(json.FromEnglish, StringComparer.OrdinalIgnoreCase);
    }

    public IReadOnlyCollection<ModelPack> Packs => _packs.Values;

    public static ModelCatalog LoadEmbedded()
    {
        using var stream = typeof(ModelCatalog).Assembly.GetManifestResourceStream("model-catalog.json")
            ?? throw new InvalidOperationException("model-catalog.json is not embedded.");
        return Parse(stream);
    }

    public static ModelCatalog Parse(Stream json)
    {
        var parsed = JsonSerializer.Deserialize(json, CatalogJsonContext.Default.CatalogJson)
            ?? throw new InvalidDataException("Empty model catalog.");
        if (parsed.Schema != 1) throw new InvalidDataException($"Unsupported catalog schema {parsed.Schema}.");
        return new ModelCatalog(parsed);
    }

    public bool CanTranslateFrom(string lang) =>
        Languages.Normalize(lang) == Languages.English || _toEnglish.ContainsKey(Languages.Normalize(lang));

    public bool CanTranslateTo(string lang) =>
        Languages.Normalize(lang) == Languages.English || _fromEnglish.ContainsKey(Languages.Normalize(lang));

    /// <summary>Languages that can be picked as "translate chat into".</summary>
    public IEnumerable<LanguageInfo> TargetLanguages => Languages.All.Where(l => CanTranslateTo(l.Code));

    /// <summary>
    /// Every pack needed to read <paramref name="chatLanguages"/> in <paramref name="reader"/>'s
    /// language and to reply into them (both directions; pivots through English included).
    /// </summary>
    public IReadOnlyList<ModelPack> PacksFor(string reader, IEnumerable<string> chatLanguages)
    {
        var packs = new Dictionary<string, ModelPack>(StringComparer.OrdinalIgnoreCase);
        foreach (var lang in chatLanguages.Select(Languages.Normalize).Distinct())
        {
            if (lang == Languages.Normalize(reader)) continue;
            foreach (var route in new[] { Route(lang, reader), Route(reader, lang) })
                foreach (var step in route ?? [])
                    packs.TryAdd(step.Pack.Id, step.Pack);
        }
        return packs.Values.ToList();
    }

    /// <summary>Whether replies can be written into <paramref name="lang"/> offline.</summary>
    public bool CanReplyOffline(string reader, string lang) => Route(reader, lang) is not null;

    /// <summary>
    /// The model steps to translate <paramref name="source"/> into <paramref name="target"/>,
    /// pivoting through English when neither side is English. Null if unsupported.
    /// </summary>
    public IReadOnlyList<RouteStep>? Route(string source, string target)
    {
        source = Languages.Normalize(source);
        target = Languages.Normalize(target);
        if (source == target) return [];

        var steps = new List<RouteStep>(2);
        if (source != Languages.English)
        {
            if (!_toEnglish.TryGetValue(source, out var id) || !_packs.TryGetValue(id, out var pack)) return null;
            steps.Add(new RouteStep(pack, null));
        }
        if (target != Languages.English)
        {
            if (!_fromEnglish.TryGetValue(target, out var dir) || !_packs.TryGetValue(dir.Pack, out var pack)) return null;
            steps.Add(new RouteStep(pack, dir.Prefix));
        }
        return steps;
    }

    internal sealed record CatalogJson(
        int Schema,
        List<ModelPack> Packs,
        Dictionary<string, string> ToEnglish,
        Dictionary<string, DirectionalPack> FromEnglish);
}

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(ModelCatalog.CatalogJson))]
internal sealed partial class CatalogJsonContext : JsonSerializerContext;
